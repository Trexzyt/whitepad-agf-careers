/* =========================================
   JOB MODAL
========================================= */

const modal = document.getElementById("jobModal");
const modalClose = document.getElementById("modalClose");
const modalOverlay = document.getElementById("modalOverlay");

const modalCategory =
    document.getElementById("modalCategory");

const modalTitle =
    document.getElementById("modalTitle");

const modalDescription =
    document.getElementById("modalDescription");

const modalApply =
    document.getElementById("modalApply");


document.querySelectorAll(".job-details").forEach(button => {

    button.addEventListener("click", () => {

        const jobId = button.dataset.job;

        const job = jobs[jobId];

        if (!job) return;

        modalCategory.textContent =
            `${job.organization} • ${job.category}`;

        modalTitle.textContent =
            job.title;

        modalDescription.innerHTML =
            job.description;


        const email =
            job.organization === "WHITEPAD"
                ? WHITEPAD_EMAIL
                : AGF_EMAIL;


        modalApply.href =
            `mailto:${email}?subject=${encodeURIComponent(
                job.organization + " Application - " + job.title
            )}`;


        modal.classList.add("active");

        document.body.style.overflow = "hidden";

    });

});


function closeModal() {

    modal.classList.remove("active");

    document.body.style.overflow = "";

}


modalClose.addEventListener(
    "click",
    closeModal
);

modalOverlay.addEventListener(
    "click",
    closeModal
);


document.addEventListener(
    "keydown",
    event => {

        if (event.key === "Escape") {
            closeModal();
        }

    }
);


/* =========================================
   MOBILE MENU
========================================= */

const menuToggle =
    document.getElementById("menuToggle");

const navLinks =
    document.querySelector(".nav-links");


menuToggle.addEventListener(
    "click",
    () => {

        navLinks.classList.toggle(
            "mobile-open"
        );

    }
);


/* Close mobile menu after clicking */

document.querySelectorAll(".nav-links a").forEach(link => {

    link.addEventListener("click", () => {

        navLinks.classList.remove(
            "mobile-open"
        );

    });

});


/* =========================================
   NAVBAR BACKGROUND
========================================= */

window.addEventListener("scroll", () => {

    const navbar =
        document.querySelector(".navbar");

    if (window.scrollY > 80) {

        navbar.style.background =
            "rgba(0,0,0,.9)";

        navbar.style.backdropFilter =
            "blur(10px)";

    } else {

        navbar.style.background =
            "transparent";

        navbar.style.backdropFilter =
            "none";

    }

});
